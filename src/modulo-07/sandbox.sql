SELECT
    c.NOM_CURSO,
    COUNT(*) AS "TOTAL_ALUNOS"

FROM ACADEMICO.ALUNOS a

JOIN ACADEMICO.CURSOS c
    ON a.COD_CURSO = c.COD_CURSO

WHERE c.COD_CURSO = 13

GROUP BY c.NOM_CURSO

ORDER BY "TOTAL_ALUNOS" DESC
;

